import { build } from 'esbuild'
import { writeFileSync, mkdirSync, rmSync } from 'node:fs'
import { fileURLToPath, pathToFileURL } from 'node:url'
import { dirname, resolve } from 'node:path'

// Guardrail #2 (PUBLISHED = SHIPPED): the /standard page renders EXACTLY what the tribunal grades.
// This script bundles the tribunal's own standard module from source and emits a generated TS
// module for the web app. It runs on every `predev`/`prebuild`, so the page cannot drift from the
// grader — regeneration is part of the build, not a manual step.

const here = dirname(fileURLToPath(import.meta.url))
const webRoot = resolve(here, '..')
const packagesRoot = resolve(webRoot, '../../packages')

const resolvePlugin = {
  name: 'assay-resolve',
  setup(b) {
    b.onResolve({ filter: /^@xyndicate\// }, (args) => ({
      path: resolve(packagesRoot, `${args.path.slice('@xyndicate/'.length)}/src/index.ts`),
    }))
    b.onResolve({ filter: /.*/ }, (args) => {
      if (args.kind === 'entry-point') return null
      if (args.path.startsWith('.') || args.path.startsWith('/')) return null
      return { path: args.path, external: true }
    })
  },
}

const tmp = resolve(webRoot, '.standard-gen')
mkdirSync(tmp, { recursive: true })

await build({
  entryPoints: {
    tribunal: resolve(packagesRoot, 'tribunal/src/index.ts'),
    core: resolve(packagesRoot, 'assay-core/src/index.ts'),
    toolspec: resolve(packagesRoot, 'mcp-server/src/toolspec.ts'),
  },
  outdir: tmp,
  bundle: true,
  platform: 'node',
  format: 'esm',
  target: 'node22',
  logLevel: 'silent',
  plugins: [resolvePlugin],
  banner: {
    js: "import { createRequire as __cr } from 'node:module'; const require = __cr(import.meta.url);",
  },
})

const mod = await import(pathToFileURL(resolve(tmp, 'tribunal.js')).href)
const core = await import(pathToFileURL(resolve(tmp, 'core.js')).href)
const spec = await import(pathToFileURL(resolve(tmp, 'toolspec.js')).href)
const { ASSAY_STANDARD, renderStandardMarkdown } = mod
const { TOOL_PRICES } = core
const markdown = renderStandardMarkdown()
const toolDocs = spec.toolDocs()

const out = `// GENERATED by scripts/gen-standard.mjs — DO NOT EDIT.
// Source of truth: packages/tribunal/src/standard.ts (the same module the grader runs).
// Regenerated on every build (predev/prebuild) so the page cannot drift from the code.

export interface StandardHardCheck {
  id: string
  title: string
  description: string
}

export interface StandardCraftAxis {
  id: string
  title: string
  weight: number
  description: string
}

export interface PublishedStandard {
  version: string
  craftPassMean: number
  craftAxisFloor: number
  repairLimit: number
  hardChecks: StandardHardCheck[]
  craftAxes: StandardCraftAxis[]
  artifactProfiles: Array<{ kind: string; checks: string[] }>
}

export const STANDARD: PublishedStandard = ${JSON.stringify(ASSAY_STANDARD, null, 2)}

export const STANDARD_MARKDOWN: string = ${JSON.stringify(markdown)}

// The fixed price table (guardrail #5) — read from assay-core, the same source the paywall reads.
export const TOOL_PRICES: Record<string, number> = ${JSON.stringify(TOOL_PRICES, null, 2)}

// Tool reference — generated from packages/mcp-server/src/toolspec.ts (the zod schemas the MCP
// server registers). Published schemas are the shipped schemas.
export interface ToolArgDoc {
  name: string
  type: string
  required: boolean
  description: string
}

export interface ToolDoc {
  name: string
  title: string
  marketplaceSummary: string
  description: string
  priceUsdt: number
  args: ToolArgDoc[]
}

export const TOOLS: ToolDoc[] = ${JSON.stringify(toolDocs, null, 2)}
`

mkdirSync(resolve(webRoot, 'lib'), { recursive: true })
writeFileSync(resolve(webRoot, 'lib/standard.generated.ts'), out)
rmSync(tmp, { recursive: true, force: true })
console.log(
  `[assay-web] standard.generated.ts — AS ${ASSAY_STANDARD.version}, ${ASSAY_STANDARD.hardChecks.length} hard checks, ${ASSAY_STANDARD.craftAxes.length} craft axes`,
)
