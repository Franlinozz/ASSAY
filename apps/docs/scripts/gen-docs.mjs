import { build } from 'esbuild'
import { writeFileSync, mkdirSync, readFileSync, rmSync } from 'node:fs'
import { fileURLToPath, pathToFileURL } from 'node:url'
import { dirname, resolve } from 'node:path'

// Generates one docs page per MCP tool from zod, the Standard mirror from grading code, and
// fictional case studies from the sealed gallery data. Runs on every predev/prebuild.

const here = dirname(fileURLToPath(import.meta.url))
const docsRoot = resolve(here, '..')
const packagesRoot = resolve(docsRoot, '../../packages')
const outDir = resolve(docsRoot, 'content/docs')

const resolvePlugin = {
  name: 'assay-resolve',
  setup(b) {
    // Fumadocs 16 owns Zod 4 inside the docs workspace, while the shipped MCP schemas deliberately
    // remain on Zod 3. Bundle that exact root dependency so schema introspection cannot cross Zod
    // realms or silently erase descriptions/types.
    b.onResolve({ filter: /^zod$/ }, () => ({
      path: resolve(packagesRoot, '../node_modules/zod/index.js'),
    }))
    b.onResolve({ filter: /^@xyndicate\// }, (args) => ({
      path: resolve(packagesRoot, `${args.path.slice('@xyndicate/'.length)}/src/index.ts`),
    }))
    b.onResolve({ filter: /.*/ }, (args) => {
      if (args.kind === 'entry-point') return null
      if (args.path.startsWith('.') || args.path.startsWith('/')) return null
      return { path: args.path, external: true }
    })
  },
}

const tmp = resolve(docsRoot, '.docs-gen')
mkdirSync(tmp, { recursive: true })

await build({
  entryPoints: {
    toolspec: resolve(packagesRoot, 'mcp-server/src/toolspec.ts'),
    tribunal: resolve(packagesRoot, 'tribunal/src/index.ts'),
  },
  outdir: tmp,
  bundle: true,
  platform: 'node',
  format: 'esm',
  target: 'node22',
  logLevel: 'silent',
  plugins: [resolvePlugin],
  banner: {
    js: "import { createRequire as __cr } from 'node:module'; const require = __cr(import.meta.url);",
  },
})

const spec = await import(pathToFileURL(resolve(tmp, 'toolspec.js')).href)
const tribunal = await import(pathToFileURL(resolve(tmp, 'tribunal.js')).href)
const tools = spec.toolDocs()
const standardMd = tribunal.renderStandardMarkdown()
const personaBundle = JSON.parse(
  readFileSync(resolve(docsRoot, '../web/lib/personas.generated.json'), 'utf8'),
)

// MDX-safe prose: braces/angles would parse as JSX expressions.
const esc = (s) =>
  s
    .replaceAll('{', '&#123;')
    .replaceAll('}', '&#125;')
    .replaceAll('<', '&lt;')
    .replaceAll('>', '&gt;')

const toolsDir = resolve(outDir, 'tools')
rmSync(resolve(outDir, 'tools.mdx'), { force: true })
rmSync(toolsDir, { recursive: true, force: true })
mkdirSync(toolsDir, { recursive: true })

const toolRows = []
const callExamples = {
  asy_ats_scan: {
    resumeText: 'Ada Example\nEXPERIENCE\nProduct Analyst\nSKILLS\nSQL',
    jd: 'Product analyst with SQL',
  },
  asy_claim_audit: {
    claims: ['Reduced onboarding time by 18%', 'Led the team'],
    resumeText: 'Quarterly review: onboarding time fell by 18%.',
  },
  asy_fit_brief: {
    jd: 'Product analyst with SQL and dashboarding experience',
    claims: ['Built weekly SQL operations dashboards'],
  },
  asy_cover_letter: {
    dossierId: 'DSR-WC0Q7NZ7',
    jd: 'Product Operations Lead',
  },
  asy_story_bank: { dossierId: 'DSR-WC0Q7NZ7' },
  asy_interview_prep: {
    dossierId: 'DSR-WC0Q7NZ7',
    answer: 'Situation: … Task: … Action: … Result: …',
  },
  asy_tailor_resume: {
    dossierId: 'DSR-WC0Q7NZ7',
    jd: 'Product Operations Lead',
  },
  asy_create_dossier_job: {
    resumeText: 'Ada Example\nEXPERIENCE\nProduct Analyst\nSKILLS\nSQL',
    jd: 'Product analyst with SQL',
    variant: 'job',
  },
  asy_job_status: { jobId: 'job_…' },
  asy_job_result: { jobId: 'job_…' },
  asy_order_result: { receipt: 'ord_…' },
  asy_verify: { dossierId: 'DSR-WC0Q7NZ7' },
}
for (const tool of tools) {
  const price = tool.priceUsdt > 0 ? `${tool.priceUsdt.toFixed(2)} USDT` : 'free'
  const args =
    tool.args.length === 0
      ? '_No arguments._'
      : [
          '| Argument | Type | Required | Description |',
          '| --- | --- | --- | --- |',
          ...tool.args.map(
            (arg) =>
              `| \`${arg.name}\` | \`${arg.type}\` | ${arg.required ? 'yes' : 'no'} | ${esc(arg.description)} |`,
          ),
        ].join('\n')
  const exampleArgs = callExamples[tool.name]
  if (!exampleArgs) throw new Error(`missing docs call example for ${tool.name}`)
  for (const key of Object.keys(exampleArgs))
    if (!tool.args.some((arg) => arg.name === key))
      throw new Error(`${tool.name} docs example uses unknown argument ${key}`)
  writeFileSync(
    resolve(toolsDir, `${tool.name}.mdx`),
    `---
title: ${JSON.stringify(tool.name)}
description: ${JSON.stringify(tool.marketplaceSummary)}
---

{/* GENERATED by scripts/gen-docs.mjs from packages/mcp-server/src/toolspec.ts — DO NOT EDIT. */}

# \`${tool.name}\` — ${esc(tool.title)}

**Price:** ${price}${tool.priceUsdt === 0 ? ' · no payment challenge' : ' · x402 on X Layer'}

${esc(tool.description)}

## Input schema

${args}

## JSON-RPC call shape

\`\`\`json
${JSON.stringify(
  {
    jsonrpc: '2.0',
    id: 1,
    method: 'tools/call',
    params: { name: tool.name, arguments: exampleArgs },
  },
  null,
  2,
)}
\`\`\`

Call the stateless Streamable HTTP endpoint at \`https://api.assayed.xyz/mcp\`. See
[x402 payment notes](/docs/x402) for paid calls and the [complete tool index](/docs/tools) for
the other generated schemas.
`,
  )
  toolRows.push(
    `| [\`${tool.name}\`](/docs/tools/${tool.name}) | ${esc(tool.marketplaceSummary)} | ${price} |`,
  )
}

writeFileSync(
  resolve(toolsDir, 'index.mdx'),
  `---
title: Tools reference
description: All twelve MCP tools, with one generated schema page per tool.
---

{/* GENERATED by scripts/gen-docs.mjs from packages/mcp-server/src/toolspec.ts — DO NOT EDIT. */}

The exact table the MCP server registers. One endpoint: \`https://api.assayed.xyz/mcp\`
(streamable-HTTP, stateless). Paid tools settle via [x402](/docs/x402); \`asy_verify\`,
\`asy_job_status\` and \`asy_job_result\` are never gated.

| Tool | Purpose | Price |
| --- | --- | ---: |
${toolRows.join('\n')}
`,
)

writeFileSync(
  resolve(toolsDir, 'meta.json'),
  `${JSON.stringify({ title: 'MCP tools', pages: ['index', ...tools.map((tool) => tool.name)] }, null, 2)}\n`,
)

writeFileSync(
  resolve(outDir, 'standard.mdx'),
  `---
title: The Assay Standard
description: The grading rubric, rendered from the same code that grades.
---

{/* GENERATED by scripts/gen-docs.mjs via tribunal.renderStandardMarkdown — DO NOT EDIT. */}

This page mirrors [assayed.xyz/standard](https://assayed.xyz/standard). Both are generated from
\`packages/tribunal/src/standard.ts\` — the module the grader runs (guardrail: published = shipped).

${standardMd.trimEnd().replaceAll('{', '&#123;').replaceAll('}', '&#125;')}
`,
)

const caseDir = resolve(outDir, 'case-studies')
rmSync(caseDir, { recursive: true, force: true })
mkdirSync(caseDir, { recursive: true })
const caseRows = []
for (const persona of personaBundle.personas) {
  const counts = { strong: 0, partial: 0, confirm: 0, missing: 0 }
  for (const row of persona.coverage) counts[row.status] = (counts[row.status] ?? 0) + 1
  const missing = persona.coverage
    .filter((row) => row.status === 'missing')
    .map((row) => `- ${esc(row.requirement)}`)
    .join('\n')
  writeFileSync(
    resolve(caseDir, `${persona.slug}.mdx`),
    `---
title: ${JSON.stringify(persona.name)}
description: "Fictional persona demonstration generated by the real Assay pipeline."
---

> **Fictional persona — demonstration.** ${persona.name}, their history, contact details, and
> target role are invented test data. The pipeline outputs, Chromium parse-back, Tribunal reports,
> and X Layer commitment are real.

# ${persona.name}

**${persona.headline}** · ${persona.caseType}

${persona.blurb}

- **Dossier:** \`${persona.dossierId}\`
- **Provider mode:** deterministic fake LLM adapter; every non-LLM pipeline stage is production code
- **Coverage:** ${counts.strong} strong · ${counts.partial} partial · ${counts.confirm} confirm · ${counts.missing} missing
- **ATS parse-back:** ${persona.parseBack.fidelityPct}% across ${persona.parseBack.fieldsChecked} checked fields
- **Original sealed report:** ${persona.tribunal.rollup.finalPassed}/${persona.tribunal.rollup.artifacts} artifacts passed AS-1.0.0 after the bounded repair loop
- **Honest AS-1.1.0 re-grade:** ${persona.as11Regrade.rollup.finalPassed}/${persona.as11Regrade.rollup.artifacts} artifacts pass; the old seal and report remain unchanged

## Gaps Assay refused to hide

${missing || '_No missing coverage rows._'}

## Verify the exhibit

- [Open the complete gallery dossier](https://assayed.xyz/gallery/${persona.slug})
- [Check \`${persona.dossierId}\` in the verifier](https://assayed.xyz/verify)
- [Inspect the real X Layer seal transaction](${persona.seal.explorerLink})

The seal proves the canonical artifact set has not changed. It does not prove that a fictional
career claim is objectively true; the evidence tier communicates that separate question.
`,
  )
  caseRows.push(
    `| [${persona.name}](/docs/case-studies/${persona.slug}) | ${persona.caseType} | \`${persona.dossierId}\` | ${persona.as11Regrade.rollup.finalPassed}/${persona.as11Regrade.rollup.artifacts} |`,
  )
}

writeFileSync(
  resolve(caseDir, 'index.mdx'),
  `---
title: Persona case studies
description: Clearly fictional personas, real pipeline output, real mainnet seals.
---

# Persona case studies

Every person below is fictional demonstration data. Each dossier ran through extraction, the claim
gate, coverage, Forge, the Tribunal repair loop, Chromium PDF parse-back, and a real X Layer
commitment. The deterministic fake LLM adapter keeps the exhibits reproducible and zero-spend.

| Persona | Case | Dossier | AS-1.1 re-grade |
| --- | --- | --- | ---: |
${caseRows.join('\n')}
`,
)
writeFileSync(
  resolve(caseDir, 'meta.json'),
  `${JSON.stringify(
    {
      title: 'Case studies',
      pages: ['index', ...personaBundle.personas.map((persona) => persona.slug)],
    },
    null,
    2,
  )}\n`,
)

rmSync(tmp, { recursive: true, force: true })
console.log(
  `[assay-docs] generated ${tools.length} tool pages + standard.mdx + ${personaBundle.personas.length} fictional case studies`,
)
